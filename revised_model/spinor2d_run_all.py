def wkb_field(Bbar,Btrans,d,mask):
 if OMEGA_ATTEMPT is None or OMEGA_MODE_OFFSET is None: raise RuntimeError("Extract confinement spectrum before WKB evaluation")
 Beff=np.maximum(Bbar+Btrans[mask],CFG["barrier_floor_T"])
 forbidden=np.maximum(GAMMA*Beff-OMEGA_MODE_OFFSET,0.)
 action=d*np.sqrt(forbidden/D)
 # Leading-order symmetric-double-well WKB gives the angular eigenfrequency
 # splitting Delta_omega=(omega_well/pi) exp(-S).  The spinor Hamiltonian below
 # has off-diagonal angular coupling K_omega, whose eigenfrequency splitting is
 # 2*K_omega.  Therefore K_omega=Delta_omega/2.  Keeping this factor of two
 # explicit prevents confusing mode splitting with Hamiltonian coupling.
 delta_omega=(OMEGA_ATTEMPT/np.pi)*np.exp(-action)
 K_omega=0.5*delta_omega
 return K_omega,Beff,action

def simple_truth(K0,K1,nt=1800,refine=True):
 """Common-pulse, loss-inclusive two-level screen with local time refinement.

 The same time is used for both control states.  A coarse scan locates several
 candidate maxima; bounded scalar minimisation then removes time-grid bias.
 """
 tmax=CFG["gate_search_max_s"]
 def metrics(t):
  surv=math.exp(-2*ALPHA*OMEGA_BEC*t)
  c0=math.cos(2*np.pi*K0*t)**2
  c1=math.sin(2*np.pi*K1*t)**2
  return surv*min(c0,c1),min(c0,c1),surv
 ts=np.linspace(0,tmax,nt+1)
 surv_vec=np.exp(-2*ALPHA*OMEGA_BEC*ts)
 cond_vec=np.minimum(np.cos(2*np.pi*K0*ts)**2,np.sin(2*np.pi*K1*ts)**2)
 vals=surv_vec*cond_vec
 if not refine:
  j=int(np.argmax(vals))
  return {"Fabs":float(vals[j]),"time_s":float(ts[j]),
          "Fcond":float(cond_vec[j]),"survival":float(surv_vec[j])}
 # Refine the strongest separated coarse candidates; the objective contains a
 # min() cusp, so relying on only one local interval is unsafe.
 order=np.argsort(vals)[::-1]; chosen=[]; best=(-1.,0.,0.,0.)
 dt=ts[1]-ts[0]
 for j in order:
  if j==0 or j==len(ts)-1: continue
  if any(abs(int(j)-q)<=2 for q in chosen): continue
  chosen.append(int(j))
  lo=max(0.,ts[j]-2*dt); hi=min(tmax,ts[j]+2*dt)
  opt=minimize_scalar(lambda t:-metrics(float(t))[0],bounds=(lo,hi),method="bounded",
                      options={"xatol":max(1e-15,dt*1e-6)})
  fabs,fcond,surv=metrics(float(opt.x))
  if fabs>best[0]: best=(fabs,float(opt.x),fcond,surv)
  if len(chosen)>=12: break
 return {"Fabs":float(best[0]),"time_s":float(best[1]),
         "Fcond":float(best[2]),"survival":float(best[3])}


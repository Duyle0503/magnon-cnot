  for jy,jx,h in ((iy-1,ix,M["dy"]),(iy+1,ix,M["dy"]),(iy,ix-1,M["dx"]),(iy,ix+1,M["dx"])):
   if 0<=jy<mask.shape[0] and 0<=jx<mask.shape[1] and mask[jy,jx]: rr.append(p);cc.append(ids[jy,jx]);dd.append(-D/h**2)

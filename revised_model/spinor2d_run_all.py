def equivalent_receiver_source_mask(M,control_y,control_radius):
 """Reduced footprint of the receiver-driven equivalent magnetic source.

 The footprint follows the declared control-mode aperture solely to define a
 reproducible spatial transfer kernel. It is not a second control-dependent
 material geometry and does not assert a static-field difference for +/-q.
 """
 return (M["X"]-CFG["control_x_m"])**2+(M["Y"]-control_y)**2<=control_radius**2

def unit_receiver_transduced_field(M,mask=None,zsep=None):
 """Unit-amplitude barrier-field transfer template of the equivalent source.

 A fully driven receiver/transducer is represented by a longitudinal equivalent
 magnetic source sheet, delta M_y=-Ms, over the declared footprint. The actual
 source amplitude is supplied by the same nonlinear cone map after multiplying
 by the coherent receiver overlap. Thus the returned field is a transfer
 template, not the raw static demagnetising field of a +/-q condensate and not
 an RF-circuit simulation.
 """
 mask=M["control"] if mask is None else mask
 zsep=CFG["control_target_vertical_separation_m"] if zsep is None else zsep
 ny,nx=M["ny"],M["nx"]; py,px=2*ny,2*nx
 kx=2*np.pi*cp.fft.rfftfreq(px,M["dx"]); ky=2*np.pi*cp.fft.fftfreq(py,M["dy"])
 KY,KX=cp.meshgrid(ky,kx,indexing="ij"); K=cp.sqrt(KX*KX+KY*KY); q=K*CFG["film_thickness_m"]
 F=cp.where(K>0,(1-cp.exp(-q))/cp.maximum(q,1e-300),1.); Nyy=cp.where(K>0,(1-F)*KY*KY/(K*K),0.)
 My=cp.zeros((py,px),cp.float64); My[:ny,:nx]=-MS*cp.asarray(mask)
 # Cross-layer propagation: every in-plane Fourier component decays as
 # exp(-k*zsep). This removes the unphysical same-plane overlap while retaining
 # the declared thin-film approximation.
 cross_layer=cp.exp(-K*zsep)
 By=-MU0*cp.fft.irfft2(Nyy*cross_layer*cp.fft.rfft2(My),s=(py,px)).real[:ny,:nx]
